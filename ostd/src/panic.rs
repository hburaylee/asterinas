//! Panic support.

#[cfg(any(feature = "kernelet", ktest))]
use core::fmt::{self, Write};

use crate::early_println;
#[cfg(any(feature = "kernelet", ktest))]
use crate::sync::SpinLock;

extern crate gimli;

#[cfg(any(feature = "kernelet", ktest))]
#[derive(Clone)]
struct BoundedMessage {
    bytes: [u8; 1024],
    len: usize,
}

#[cfg(any(feature = "kernelet", ktest))]
impl BoundedMessage {
    fn format(message: fmt::Arguments<'_>) -> Self {
        let mut record = Self {
            bytes: [0; 1024],
            len: 0,
        };
        // Reaching the fixed capacity deliberately stops formatting.
        let _ = record.write_fmt(message);
        record
    }

    fn as_str(&self) -> &str {
        core::str::from_utf8(&self.bytes[..self.len]).unwrap()
    }
}

#[cfg(any(feature = "kernelet", ktest))]
impl Write for BoundedMessage {
    fn write_str(&mut self, text: &str) -> fmt::Result {
        let mut len = text.len().min(self.bytes.len() - self.len);
        while !text.is_char_boundary(len) {
            len -= 1;
        }
        self.bytes[self.len..self.len + len].copy_from_slice(&text.as_bytes()[..len]);
        self.len += len;
        if len < text.len() {
            Err(fmt::Error)
        } else {
            Ok(())
        }
    }
}

#[cfg(feature = "kernelet")]
static PANIC_MESSAGE: SpinLock<Option<BoundedMessage>> = SpinLock::new(None);

#[cfg(any(feature = "kernelet", ktest))]
fn stash_message(slot: &SpinLock<Option<BoundedMessage>>, message: fmt::Arguments<'_>) {
    // A user Display implementation can panic. Format before taking the lock
    // so a recursive panic cannot deadlock on PANIC_MESSAGE.
    let record = BoundedMessage::format(message);
    let mut slot = slot.disable_irq().lock();
    // The first completed message to acquire this lock wins, even if empty.
    // Later caught panics still report an oops, without replacing this record.
    slot.get_or_insert(record);
}

/// Records a fatal message before an allocation failure or explicit abort.
///
/// Native kernels retain their existing panic behavior. A kernelet retains
/// the first committed message, truncated at a UTF-8 boundary to 1 KiB.
#[doc(hidden)]
pub fn __stash_message(message: core::fmt::Arguments<'_>) {
    #[cfg(feature = "kernelet")]
    stash_message(&PANIC_MESSAGE, message);
    #[cfg(not(feature = "kernelet"))]
    let _ = message;
}

/// Enters a panic handler generated by OSTD's proc macros.
#[doc(hidden)]
pub fn __handler_entry(info: &core::panic::PanicInfo<'_>) {
    #[cfg(feature = "kernelet")]
    if let Some(location) = info.location() {
        __stash_message(format_args!(
            "{} at {}:{}:{}",
            info.message(),
            location.file(),
            location.line(),
            location.column(),
        ));
    } else {
        __stash_message(format_args!("{}", info.message()));
    }
    #[cfg(not(feature = "kernelet"))]
    let _ = info;
}

#[cfg(feature = "kernelet")]
fn stashed_message() -> BoundedMessage {
    // No panic lock spans a Host service call or user-provided formatting.
    let record = PANIC_MESSAGE.disable_irq().lock().clone();
    record.unwrap_or_else(|| BoundedMessage::format(format_args!("abort")))
}

/// The default panic handler for OSTD based kernels.
///
/// The user can override it by defining their own panic handler with the macro
/// `#[ostd::panic_handler]`.
#[linkage = "weak"]
// SAFETY: The name does not collide with other symbols.
#[unsafe(no_mangle)]
pub fn __ostd_panic_handler(info: &core::panic::PanicInfo) -> ! {
    __handler_entry(info);
    let _irq_guard = crate::irq::disable_local();

    crate::cpu_local_cell! {
        static IN_PANIC: bool = false;
    }

    if IN_PANIC.load() {
        early_println!("The panic handler panicked {:#?}", info);
        abort();
    }

    IN_PANIC.store(true);

    early_println!("Non-resettable panic! {:#?}", info);

    print_stack_trace();
    abort();
}

/// Aborts the system.
///
/// A kernelet reports an unrecoverable panic to its Host. A native kernel first
/// attempts to power off the system and otherwise halts all CPUs.
pub fn abort() -> ! {
    #[cfg(feature = "kernelet")]
    {
        let message = stashed_message();
        crate::kernelet::entry::stop_panic(format_args!("{}", message.as_str()));
    }

    #[cfg(not(feature = "kernelet"))]
    {
        // TODO: The main purpose of powering off here is to allow QEMU to exit. Otherwise, the CI may
        // freeze after panicking. However, this is unnecessary and may prevent debugging on a real
        // machine (i.e., the message will disappear afterward).
        crate::power::poweroff(crate::power::ExitCode::Failure);
    }
}

/// A guard that aborts the system if dropped.
///
/// This is useful to ensure that certain objects will not be dropped during
/// panic handling.
#[derive(Debug)]
pub(crate) struct PanicGuard {
    _private: (),
}

impl Drop for PanicGuard {
    fn drop(&mut self) {
        early_println!("Panicked in `PanicGuard`, aborting the system");
        abort();
    }
}

impl PanicGuard {
    /// Creates a panic guard that aborts the system if dropped.
    pub(crate) fn new() -> Self {
        PanicGuard { _private: () }
    }

    /// Finishes panic guarding by forgetting the guard.
    ///
    /// After the panic guarding finishes, it no longer aborts the system
    /// when panic happens.
    pub(crate) fn forget(self) {
        core::mem::forget(self);
    }
}

pub use unwinding::panic::begin_panic;
#[cfg(not(feature = "kernelet"))]
pub use unwinding::panic::catch_unwind;

/// Catches an unwind and reports each caught kernelet panic to its Host.
#[cfg(feature = "kernelet")]
pub fn catch_unwind<R, F: FnOnce() -> R>(
    f: F,
) -> Result<R, alloc::boxed::Box<dyn core::any::Any + Send>> {
    let result = unwinding::panic::catch_unwind(f);
    if result.is_err() {
        let message = stashed_message();
        let _ = crate::kernelet::entry::report_oops(message.as_str());
    }
    result
}

/// Prints the stack trace of the current thread to the console.
///
/// The printing procedure is protected by a spin lock to prevent interleaving.
pub fn print_stack_trace() {
    use core::ffi::c_void;

    use gimli::Register;
    use unwinding::abi::{
        _Unwind_Backtrace, _Unwind_FindEnclosingFunction, _Unwind_GetGR, _Unwind_GetIP,
        UnwindContext, UnwindReasonCode,
    };

    use crate::{early_print, sync::SpinLock};

    /// We acquire a global lock to prevent the frames in the stack trace from
    /// interleaving. The spin lock is used merely for its simplicity.
    static BACKTRACE_PRINT_LOCK: SpinLock<()> = SpinLock::new(());
    let _lock = BACKTRACE_PRINT_LOCK.lock();

    early_println!("Printing stack trace:");

    struct CallbackData {
        counter: usize,
    }
    extern "C" fn callback(unwind_ctx: &UnwindContext<'_>, arg: *mut c_void) -> UnwindReasonCode {
        let data = unsafe { &mut *(arg as *mut CallbackData) };
        data.counter += 1;
        let pc = _Unwind_GetIP(unwind_ctx);
        if pc > 0 {
            let fde_initial_address = _Unwind_FindEnclosingFunction(pc as *mut c_void) as usize;
            early_println!(
                "{:4}: fn {:#18x} - pc {:#18x} / registers:",
                data.counter,
                fde_initial_address,
                pc,
            );
        }
        // Print the first 8 general registers for any architecture. The register number follows
        // the DWARF standard.
        for i in 0..8u16 {
            let reg_name = cfg_select! {
                target_arch = "x86_64" => gimli::X86_64::register_name(Register(i)),
                target_arch = "riscv64" => gimli::RiscV::register_name(Register(i)),
                target_arch = "loongarch64" => gimli::LoongArch::register_name(Register(i)),
                target_arch = "aarch64" => gimli::AArch64::register_name(Register(i)),
                _ => None,
            };
            let reg_val = _Unwind_GetGR(unwind_ctx, i as i32);
            if i.is_multiple_of(4) {
                early_print!("\n    ");
            }
            early_print!(" {} {:#18x};", reg_name.unwrap_or("unknown"), reg_val);
        }
        early_print!("\n\n");
        UnwindReasonCode::NO_REASON
    }

    let mut data = CallbackData { counter: 0 };
    _Unwind_Backtrace(callback, &mut data as *mut _ as _);
}

#[cfg(ktest)]
mod test {
    use super::*;
    use crate::prelude::*;

    #[ktest]
    fn panic_message_keeps_first_committed_record() {
        let slot = SpinLock::new(None);
        stash_message(&slot, format_args!("first panic at source.rs:42"));
        stash_message(&slot, format_args!("later allocation failure"));
        assert_eq!(
            slot.lock().as_ref().unwrap().as_str(),
            "first panic at source.rs:42"
        );

        let empty_slot = SpinLock::new(None);
        stash_message(&empty_slot, format_args!(""));
        stash_message(&empty_slot, format_args!("a nonempty later panic"));
        assert_eq!(empty_slot.lock().as_ref().unwrap().as_str(), "");
    }

    #[ktest]
    fn panic_message_truncates_at_utf8_boundary_without_skipping_text() {
        let record = BoundedMessage::format(format_args!("{:1023}éZ", ""));
        assert_eq!(record.len, 1023);
        assert!(record.as_str().bytes().all(|byte| byte == b' '));

        let exact = BoundedMessage::format(format_args!("{:1022}éZ", ""));
        assert_eq!(exact.len, 1024);
        assert!(exact.as_str().ends_with('é'));
        assert!(!exact.as_str().ends_with('Z'));
    }
}
